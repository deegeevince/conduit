function words(title: string, key: string, entries: Readonly<Record<string, string>>): string {
  const rows = Object.entries(entries).map(([word, gist]) => `| \`${word}\` | ${gist} |`);
  return [`### ${title}`, '', `| ${key} | Meaning |`, '| --- | --- |', ...rows, ''].join('\n');
}

