// The faces a look or a line can name, and what the painter and the renderer
// need to know about each. A face that is not in this table does not exist.
//
// A proportional face carries the advance of every character of `GLYPHS`,
// generated from its font file (`pnpm --filter @conduit/web fonts`); the three
// retro faces and `mono` are fixed pitch and are measured as `characters x
// advance`. `mono` has a table too (`metrics/mono-400.ts`), but only to prove
// that every advance in it is the same.

import type { Face } from '@conduit/language';
import { DISPLAY_400 } from './metrics/display-400';
import { HAND_500 } from './metrics/hand-500';
import { HAND_700 } from './metrics/hand-700';
import { SANS_400 } from './metrics/sans-400';
import { SANS_700 } from './metrics/sans-700';
import { SERIF_400 } from './metrics/serif-400';
import { SERIF_700 } from './metrics/serif-700';

/** Advance widths of a proportional face, in em, for every character in `GLYPHS`. Generated by `pnpm --filter @conduit/web fonts`; never edited by hand. */
export interface FaceMetrics {
  /** em per character, keyed by the character */
  readonly advance: Readonly<Record<string, number>>;
  /** em: used for a character that is somehow not in the table */
  readonly fallback: number;
  /** em above and below the baseline, for placing marks */
  readonly ascent: number;
  readonly descent: number;
  readonly xHeight: number;
}

export interface FaceSpec {
  readonly face: Face;
  /** key into FONTS */
  readonly font: string;
  /** key into FONTS for weight=bold, or null when bold is drawn some other way */
  readonly boldFont: string | null;
  readonly bold: 'face' | 'bright' | 'none';
  readonly pitch: 'fixed' | 'proportional';
  /** cell width in em for a fixed-pitch face; the average advance of running English text for a proportional one */
  readonly advance: number;
  /** line height in em that suits the face */
  readonly lineHeight: number;
  readonly upperOnly: boolean;
  /** null for a fixed-pitch face: every character is `advance` wide */
  readonly metrics: FaceMetrics | null;
  /** null for the same file as normal weight */
  readonly boldMetrics: FaceMetrics | null;
}

const fixed = (face: Face, font: string, boldFont: string | null, bold: FaceSpec['bold'], advance: number, lineHeight: number): FaceSpec => ({
  face,
  font,
  boldFont,
  bold,
  pitch: 'fixed',
  advance,
  lineHeight,
  upperOnly: false,
  metrics: null,
  boldMetrics: null,
});

/** Relative frequency of the letters of English text, per thousand letters. */
const LETTER_FREQUENCY: Readonly<Record<string, number>> = {
  e: 127, t: 91, a: 82, o: 75, i: 70, n: 67, s: 63, h: 61, r: 60, d: 43, l: 40, c: 28, u: 28, m: 24, w: 24, f: 22, g: 20, y: 20, p: 19, b: 15, v: 10, k: 8, j: 2, x: 2, q: 1, z: 1,
};

/** The mean advance, in em, over running English: about 80% letters at their usual frequencies, 17% spaces, a little punctuation. */
function meanAdvance(metrics: FaceMetrics): number {
  const at = (char: string): number => metrics.advance[char] ?? metrics.fallback;
  let weighted = 0;
  let total = 0;
  for (const [letter, frequency] of Object.entries(LETTER_FREQUENCY)) {
    weighted += frequency * at(letter);
    total += frequency;
  }
  return Number((0.8 * (weighted / total) + 0.17 * at(' ') + 0.015 * at(',') + 0.015 * at('.')).toFixed(4));
}

const proportional = (face: Face, font: string, boldFont: string | null, bold: FaceSpec['bold'], lineHeight: number, metrics: FaceMetrics, boldMetrics: FaceMetrics | null): FaceSpec => ({
  face,
  font,
  boldFont,
  bold,
  pitch: 'proportional',
  advance: meanAdvance(metrics),
  lineHeight,
  upperOnly: false,
  metrics,
  boldMetrics,
});

export const FACES: Readonly<Record<Face, FaceSpec>> = {
  serif: proportional('serif', 'source-serif-400', 'source-serif-700', 'face', 1.4, SERIF_400, SERIF_700),
  sans: proportional('sans', 'inter-400', 'inter-700', 'face', 1.4, SANS_400, SANS_700),
  hand: proportional('hand', 'caveat-500', 'caveat-700', 'face', 1.25, HAND_500, HAND_700),
  display: proportional('display', 'archivo-black-400', null, 'none', 1.2, DISPLAY_400, null),
  mono: fixed('mono', 'jetbrains-mono-400', 'jetbrains-mono-700', 'face', 0.6, 1.4),
  terminal: fixed('terminal', 'vt323', null, 'bright', 0.4, 1.1),
  teletext: fixed('teletext', 'bedstead', null, 'none', 0.6, 1),
  dot: fixed('dot', 'doto-700', 'doto-900', 'face', 0.6, 1.25),
};
